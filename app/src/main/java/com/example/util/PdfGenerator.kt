object PdfGenerator {

    private fun getPdfFile(context: Context, filename: String): File {
        val dir = File(context.cacheDir, "pdfs").apply { mkdirs() }
        return File(dir, filename)
    }

    private fun uriForFile(context: Context, file: File): Uri {
        return FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
    }

    fun generateReceiptPdf(
        context: Context,
        schoolName: String,
        guardianName: String,
        receipt: FamilyReceipt
    ): Uri {
        val doc = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = doc.startPage(pageInfo)
        val canvas = page.canvas

        val headerPaint = Paint().apply { color = Color.rgb(21, 101, 192) }
        val whiteBold = Paint().apply {
            color = Color.WHITE
            textSize = 20f
            typeface = Typeface.DEFAULT_BOLD
        }
        val titlePaint = Paint().apply {
            color = Color.rgb(17, 34, 56)
            textSize = 16f
            typeface = Typeface.DEFAULT_BOLD
        }
        val bodyPaint = Paint().apply {
            color = Color.rgb(55, 71, 79)
            textSize = 13f
        }
        val linePaint = Paint().apply {
            color = Color.rgb(220, 230, 242)
            strokeWidth = 2f
        }

        canvas.drawRect(0f, 0f, 595f, 100f, headerPaint)
        canvas.drawText(schoolName, 40f, 48f, whiteBold)
        canvas.drawText("OFFICIAL FAMILY FEE RECEIPT", 40f, 76f, Paint(whiteBold).apply { textSize = 12f })

        var y = 145f
        canvas.drawText("Receipt No: ${receipt.name}", 40f, y, titlePaint)
        y += 28f
        canvas.drawText("Date: ${receipt.date}", 40f, y, bodyPaint)
        y += 22f
        canvas.drawText("Guardian: $guardianName", 40f, y, bodyPaint)
        y += 22f
        canvas.drawText("Payment Mode: ${receipt.mode}", 40f, y, bodyPaint)
        if (receipt.referenceNo.isNotBlank()) {
            y += 22f
            canvas.drawText("Transaction Ref: ${receipt.referenceNo}", 40f, y, bodyPaint)
        }

        y += 24f
        canvas.drawLine(40f, y, 555f, y, linePaint)
        y += 32f
        canvas.drawText("Amount Paid: INR ${"%.2f".format(receipt.amount)}", 40f, y, titlePaint)
        y += 28f
        canvas.drawText("Allocations:", 40f, y, bodyPaint)
        y += 22f
        val lines = receipt.allocationsSummary.ifBlank { "Family Fee Settlement" }.split(",", "\n")
        for (line in lines) {
            canvas.drawText("• ${line.trim()}", 56f, y, bodyPaint)
            y += 20f
        }

        y += 30f
        canvas.drawLine(40f, y, 555f, y, linePaint)
        y += 28f
        canvas.drawText("Generated by OneBook School Parent App", 40f, y, Paint(bodyPaint).apply { textSize = 11f })

        doc.finishPage(page)
        val file = getPdfFile(context, "receipt_${receipt.name.replace("/", "_")}.pdf")
        FileOutputStream(file).use { doc.writeTo(it) }
        doc.close()
        return uriForFile(context, file)
    }

    fun generateReportCardPdf(
        context: Context,
        schoolName: String,
        card: ReportCard
    ): Uri {
        val doc = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = doc.startPage(pageInfo)
        val canvas = page.canvas

        val headerPaint = Paint().apply { color = Color.rgb(13, 71, 161) }
        val whiteBold = Paint().apply {
            color = Color.WHITE
            textSize = 20f
            typeface = Typeface.DEFAULT_BOLD
        }
        val titlePaint = Paint().apply {
            color = Color.rgb(17, 34, 56)
            textSize = 15f
            typeface = Typeface.DEFAULT_BOLD
        }
        val bodyPaint = Paint().apply {
            color = Color.rgb(45, 58, 72)
            textSize = 13f
        }
        val linePaint = Paint().apply {
            color = Color.rgb(215, 226, 240)
            strokeWidth = 1.5f
        }

        canvas.drawRect(0f, 0f, 595f, 96f, headerPaint)
        canvas.drawText(schoolName, 40f, 44f, whiteBold)
        canvas.drawText("PROGRESS REPORT CARD — ${card.examName}", 40f, 72f, Paint(whiteBold).apply { textSize = 12f })

        var y = 140f
        canvas.drawText("Student: ${card.studentName} (${card.classSection})", 40f, y, titlePaint)
        y += 24f
        canvas.drawText("Overall Score: ${"%.1f".format(card.percentage)}%   |   Grade: ${card.overallGrade}", 40f, y, bodyPaint)
        y += 24f
        canvas.drawLine(40f, y, 555f, y, linePaint)
        y += 28f

        canvas.drawText("Subject", 40f, y, titlePaint)
        canvas.drawText("Marks", 360f, y, titlePaint)
        canvas.drawText("Grade", 490f, y, titlePaint)
        y += 14f
        canvas.drawLine(40f, y, 555f, y, linePaint)
        y += 24f

        for (sub in card.subjects) {
            canvas.drawText(sub.subject, 40f, y, bodyPaint)
            canvas.drawText("${sub.marksObtained.toInt()} / ${sub.maxMarks.toInt()}", 360f, y, bodyPaint)
            canvas.drawText(sub.grade, 495f, y, bodyPaint)
            y += 24f
        }

        if (card.remarks.isNotBlank()) {
            y += 20f
            canvas.drawText("Remarks: ${card.remarks}", 40f, y, bodyPaint)
        }

        doc.finishPage(page)
        val file = getPdfFile(context, "report_${card.name.replace("/", "_")}.pdf")
        FileOutputStream(file).use { doc.writeTo(it) }
        doc.close()
        return uriForFile(context, file)
    }

    fun generateCertificatePdf(
        context: Context,
        schoolName: String,
        certificate: CertificateItem
    ): Uri {
        val doc = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = doc.startPage(pageInfo)
        val canvas = page.canvas

        val headerPaint = Paint().apply { color = Color.rgb(21, 101, 192) }
        val whiteBold = Paint().apply {
            color = Color.WHITE
            textSize = 20f
            typeface = Typeface.DEFAULT_BOLD
        }
        val titlePaint = Paint().apply {
            color = Color.rgb(17, 34, 56)
            textSize = 16f
            typeface = Typeface.DEFAULT_BOLD
        }
        val bodyPaint = Paint().apply {
            color = Color.rgb(45, 58, 72)
            textSize = 13f
        }

        canvas.drawRect(0f, 0f, 595f, 100f, headerPaint)
        canvas.drawText(schoolName, 40f, 46f, whiteBold)
        canvas.drawText("${certificate.certificateType.uppercase()} CERTIFICATE", 40f, 76f, Paint(whiteBold).apply { textSize = 13f })

        var y = 150f
        canvas.drawText("Certificate Ref: ${certificate.name}", 40f, y, titlePaint)
        y += 28f
        canvas.drawText("Student: ${certificate.studentName}", 40f, y, bodyPaint)
        y += 24f
        canvas.drawText("Status: ${certificate.status}", 40f, y, bodyPaint)
        y += 24f
        canvas.drawText("Requested Date: ${certificate.requestedDate}", 40f, y, bodyPaint)
        if (certificate.reason.isNotBlank()) {
            y += 24f
            canvas.drawText("Reason: ${certificate.reason}", 40f, y, bodyPaint)
        }

        // Deterministic verification QR matrix block
        val code = certificate.verifyCode ?: certificate.name
        val qrSize = 110f
        val qrX = 40f
        val qrY = y + 40f
        val cell = qrSize / 11f
        val darkPaint = Paint().apply { color = Color.BLACK }
        val hashSeed = code.hashCode()
        for (row in 0 until 11) {
            for (col in 0 until 11) {
                val isFinder = (row < 3 && col < 3) || (row < 3 && col > 7) || (row > 7 && col < 3)
                val bit = ((hashSeed ushr ((row * 11 + col) % 31)) and 1) == 1
                if (isFinder || bit) {
                    canvas.drawRect(
                        qrX + col * cell,
                        qrY + row * cell,
                        qrX + (col + 1) * cell,
                        qrY + (row + 1) * cell,
                        darkPaint
                    )
                }
            }
        }
        canvas.drawText("Scan / Verify Code: $code", qrX + 128f, qrY + 45f, titlePaint)
        canvas.drawText(
            certificate.verifyUrl ?: "/verify/$code",
            qrX + 128f,
            qrY + 70f,
            bodyPaint
        )

        doc.finishPage(page)
        val file = getPdfFile(context, "cert_${certificate.name.replace("/", "_")}.pdf")
        FileOutputStream(file).use { doc.writeTo(it) }
        doc.close()
        return uriForFile(context, file)
    }

    fun exportDpdpJsonFile(context: Context, jsonContent: String): Uri {
        val dir = File(context.filesDir, "exports").apply { mkdirs() }
        val file = File(dir, "aanoor_parent_data_export.json")
        file.writeText(jsonContent)
        return uriForFile(context, file)
    }

    fun openPdfUri(context: Context, uri: Uri): Boolean {
        val intent = Intent(Intent.ACTION_VIEW).apply {
            setDataAndType(uri, "application/pdf")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION or Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        return runCatching {
            context.startActivity(intent)
            true
        }.getOrElse {
            shareUri(context, uri, "application/pdf", "Share PDF")
        }
    }

    fun shareToWhatsAppOrChooser(context: Context, uri: Uri, text: String) {
        val waIntent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_TEXT, text)
            setPackage("com.whatsapp")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION or Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        val launchedWa = runCatching {
            context.startActivity(waIntent)
            true
        }.getOrDefault(false)
        if (!launchedWa) {
            shareUri(context, uri, "application/pdf", text)
        }
    }

    fun shareUri(context: Context, uri: Uri, mimeType: String, title: String): Boolean {
        val send = Intent(Intent.ACTION_SEND).apply {
            type = mimeType
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_TEXT, title)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        val chooser = Intent.createChooser(send, title).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        return runCatching {
            context.startActivity(chooser)
            true
        }.getOrDefault(false)
    }
}
